// Generates lib/hijri-table.js from Node's ICU "islamic-umalqura" calendar.
// Run: node tools/gen-hijri-table.mjs [startYearAH] [endYearAH]
import { writeFileSync } from 'node:fs'

const START = Number(process.argv[2] || 1440)
const END = Number(process.argv[3] || 1500)
const fmt = new Intl.DateTimeFormat('en-u-ca-islamic-umalqura', {
  timeZone: 'UTC', day: 'numeric', month: 'numeric', year: 'numeric',
})
const DAY = 86400000
const parts = (epochDay) => {
  const o = {}
  for (const p of fmt.formatToParts(new Date(epochDay * DAY))) o[p.type] = Number(p.value)
  return o
}

// Find epoch day (days since 1970-01-01) of 1 Muharram START.
let d = Math.floor((START - 1389.8) * 354.367) // rough guess near the year start
while (!(parts(d).year === START && parts(d).month === 1 && parts(d).day === 1)) {
  const p = parts(d)
  d += p.year < START ? 20 : p.year > START ? -20 : (p.month === 1 ? -(p.day - 1) : -20)
}
const startEpochDay = d

// One 12-bit mask per year: bit (m-1) set => month m has 30 days, else 29.
const masks = []
for (let y = START; y <= END; y++) {
  let mask = 0
  for (let m = 1; m <= 12; m++) {
    let len = 0
    while (parts(d).month === m && parts(d).year === y) { d++; len++ }
    if (len !== 29 && len !== 30) throw new Error(`bad month length ${y}/${m}: ${len}`)
    if (len === 30) mask |= 1 << (m - 1)
  }
  masks.push(mask)
}

writeFileSync(new URL('../lib/hijri-table.js', import.meta.url),
`// GENERATED by tools/gen-hijri-table.mjs from ICU islamic-umalqura. Do not edit.
export const UQ_START_YEAR = ${START}
export const UQ_START_EPOCH_DAY = ${startEpochDay} // 1 Muharram ${START} = ${new Date(startEpochDay * DAY).toISOString().slice(0, 10)}
export const UQ_MONTH_MASKS = [${masks.join(',')}]
`)
console.log(`wrote ${masks.length} years, ${START}-${END}`)
