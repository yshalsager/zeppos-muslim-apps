"""Writes lib/text-width.js: estimated character widths for the date line, so the face can shorten a
long place name to fit (lib/i18n/text.js gregLine). The watch has no way to measure text in our
font, so it adds up these widths instead.

Every string that can appear on the date line (tools/date-line-texts.mjs) is shaped with HarfBuzz in
the font that draws it, at the date line's design text size: the bundled Naskh font for Arabic, and
Noto Sans as a stand-in for the watch's system font for the other languages. Each character's width
is its average shaped advance over all of them, so an Arabic letter's width averages its joined
forms. A safety factor is built into the widths of the characters whose estimate can be off: letters
in Naskh (Arabic joined forms, and kerned Latin in cities without an Arabic name), and every
character of the system font (it isn't really Noto Sans). Digits and punctuation in Naskh are exact,
so dates and coordinates aren't penalised.

Then it checks the result: every city's date line on each language's widest dates, built by the
face's own code, must fit the date line's box in the real font. A cut name's last Arabic letter takes
its (wider) final form, so each font has a `cut` reserve, raised until every line fits.

Run: python3 -I tools/gen-text-width.py (via `mise run :gen`).
"""
import json
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))  # -I drops the script dir
import uharfbuzz as hb  # noqa: E402
import uax9  # noqa: E402

from render import LATIN_FONT, ROOT, SCALE, device, font  # noqa: E402

# Widths are multiplied by SAFETY where it applies (see above); printed below: how often the estimate
# covers a string's real width
SAFETY = {"naskh": 1.15, "system": 1.03}


def safety(key, ch):
    return SAFETY[key] if key == "system" or ch.isalpha() else 1


def widths(f, texts, rtl):
    """Average advance per character (px at the font's size / SCALE)."""
    total, count = defaultdict(float), defaultdict(int)
    for t in texts:
        for text, run_rtl in uax9.runs(t, rtl):
            buf = hb.Buffer()
            buf.add_str(text)
            buf.guess_segment_properties()
            buf.direction = "rtl" if run_rtl else "ltr"
            hb.shape(f.hb, buf, {})
            clusters = defaultdict(float)
            for info, pos in zip(buf.glyph_infos, buf.glyph_positions):
                clusters[info.cluster] += pos.x_advance / 64 / SCALE
            starts = sorted(clusters)
            for i, c in enumerate(starts):  # a ligature's advance is shared by its characters
                seg = text[c:starts[i + 1] if i + 1 < len(starts) else len(text)]
                for ch in seg:
                    total[ch] += clusters[c] / len(seg)
                    count[ch] += 1
    return {ch: total[ch] / count[ch] for ch in total}


def main():
    dev = device()
    size = dev.L["greg"]["text_size"]
    texts = json.loads(subprocess.check_output(["node", str(ROOT / "tools" / "date-line-texts.mjs")], cwd=ROOT))
    out = {"size": size}
    for key, path, rtl in (("naskh", dev.arabic_font, True), ("system", LATIN_FONT, False)):
        f = font(path, size * SCALE)
        w = {c: v * safety(key, c) for c, v in widths(f, texts[key], rtl).items()}
        est = lambda s: sum(w[c] for c in s)  # noqa: E731
        ratios = sorted(f.width(t, rtl) / SCALE / est(t) for t in texts[key] if est(t) > 20)
        covered = sum(r <= 1 for r in ratios) * 100 / len(ratios)
        print(f"{key}: {len(w)} characters, the estimate covers {covered:.1f}% of {len(ratios)} strings "
              f"(worst: real = {ratios[-1]:.2f} × estimate)")
        out[key] = {"cut": 0, "other": round(max(w.values()), 1), "w": {c: round(v, 1) for c, v in sorted(w.items())}}
    while True:
        write(out)
        over = check(dev)
        if not over:
            break
        for key in {"naskh" if lang == "ar" else "system" for lang, _, _ in over}:
            if out[key]["cut"] >= 40:
                sys.exit(f"date lines wider than the box: {over[:5]}")
            out[key]["cut"] += 2
    print(f"cut reserve: naskh {out['naskh']['cut']} px, system {out['system']['cut']} px")


def write(out):
    js = ("// GENERATED by tools/gen-text-width.py. Do not edit.\n"
          "// Estimated advance width of each character on the date line, in px at text size `size`, per font\n"
          "// (naskh: Arabic; system: the other languages), with a safety margin built in; `other` for\n"
          "// characters not listed, `cut` the extra room a shortened name needs. lib/i18n/text.js uses it\n"
          "// to shorten a long place name.\n"
          f"export const TEXT_WIDTH = {json.dumps(out, ensure_ascii=False, separators=(',', ':'))}\n")
    (ROOT / "lib" / "text-width.js").write_text(js)


def check(dev):
    """[(lang, width, line)] of the face's date lines wider than their box."""
    check = json.loads(subprocess.check_output(["node", str(ROOT / "tools" / "date-line-texts.mjs"), "--lines"], cwd=ROOT))
    box = check["box"]
    over = []
    for lang, lines in check["lines"].items():
        rtl = lang == "ar"  # lib/i18n: the only right-to-left language
        f = font(dev.arabic_font if rtl else LATIN_FONT, box["text_size"] * SCALE)
        widest = 0
        for s in lines:
            w = f.width(s.lstrip("\u200f"), rtl) / SCALE  # line() may start with an RLM
            widest = max(widest, w)
            if w > box["w"]:
                over.append((lang, round(w), s))
        cut = sum(s.endswith("…") for s in lines)
        print(f"  {lang}: {len(lines)} date lines, widest {round(widest)} of {box['w']} px, {cut * 100 // len(lines)}% shortened")
    return over


if __name__ == "__main__":
    main()
