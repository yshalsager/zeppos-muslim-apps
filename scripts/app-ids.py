"""Writes the app IDs from the root mise.toml's [env] where they're needed. Run by each project's :gen.

The IDs are the ones registered on the Zepp developer console (console.zepp.com):
  PRAYER_TIMES_APP_ID     the watchface
  PRAYER_LOCATION_APP_ID  the location companion; the face reads its shared location by this ID
  DAAD_KEYBOARD_APP_ID    the Daad keyboard
  SLEEP_TIME_APP_ID       the Sleep Time app

  python3 scripts/app-ids.py PROJECT   (a folder name, e.g. prayer-times-watchface)

zeus can't pass environment variables into the watch code, so they're written into files:
  <project>/app.json                      appId (in place, keeping the file's formatting)
  prayer-times-watchface/lib/app-ids.js   LOCATION_APP_ID, for lib/location.js
"""
import os
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OWN_ID = {"prayer-times-watchface": "PRAYER_TIMES_APP_ID", "prayer-location-app": "PRAYER_LOCATION_APP_ID",
          "daad-keyboard": "DAAD_KEYBOARD_APP_ID", "sleep-time": "SLEEP_TIME_APP_ID"}


def app_id(var):
    v = os.environ.get(var, "")
    if not v.isdigit():
        sys.exit(f"{var} must be set to the app's numeric ID (root mise.toml [env]); run through mise")
    return int(v)


def write(path, text):
    if not path.exists() or path.read_text() != text:  # leave the file alone when nothing changed
        path.write_text(text)
        print(f"wrote {path.relative_to(ROOT)}")


def main(project):
    if project not in OWN_ID:
        sys.exit(f"unknown project {project!r}; expected one of {sorted(OWN_ID)}")
    own = app_id(OWN_ID[project])
    location = app_id("PRAYER_LOCATION_APP_ID")  # every ID is read before anything is written
    manifest = ROOT / project / "app.json"
    new, n = re.subn(r'("appId":\s*)\d+', rf"\g<1>{own}", manifest.read_text(), count=1)
    if n != 1:
        sys.exit(f"no appId in {manifest}")
    write(manifest, new)
    if project == "prayer-times-watchface":
        write(ROOT / project / "lib" / "app-ids.js",
              "// Generated by scripts/app-ids.py from the root mise.toml's [env]; don't edit.\n"
              f"export const LOCATION_APP_ID = {location} // prayer-location-app\n")


if __name__ == "__main__":
    main(*sys.argv[1:])
